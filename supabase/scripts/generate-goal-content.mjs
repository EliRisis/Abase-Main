// Generates supabase/migrations/20260922010000_position_specific_goal_content.sql
// from the plan definitions in this folder. Run: node supabase/scripts/generate-goal-content.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { EXISTING, NEW_EXERCISES } from "./catalog.mjs";
import football from "./plans-football.mjs";
import basketball from "./plans-basketball.mjs";
import soccer from "./plans-soccer.mjs";
import baseball from "./plans-baseball.mjs";

const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../migrations/20260922010000_position_specific_goal_content.sql");
const plans = [...football, ...basketball, ...soccer, ...baseball];

const DAYS = [1, 3, 5]; // existing schedule rows are Mon/Wed/Fri
const LETTERS = ["a", "b", "c"];
const PHASES = ["Foundation", "Build", "Intensify", "Peak"];
const PHASES_CARE = ["Activate", "Build", "Strengthen", "Sustain"];
const PROGRESSION = {
  speed: "Progression: weeks 1-2 groove mechanics at about 90% effort with full rest; weeks 3-4 add resisted and flying volume. Stop a sprint set the moment speed drops.",
  strength_power: "Progression: weeks 1-2 leave 2 reps in reserve; weeks 3-4 add 2.5-5% load or a rep once every set is clean. Move power work fast and stop when bar speed fades.",
  agility_lateral_quickness: "Progression: weeks 1-2 learn each pattern under control; weeks 3-4 add reactive cues (a partner call or visual signal) and shorten rest.",
  conditioning: "Progression: weeks 1-2 build the aerobic base at a controlled pace; weeks 3-4 trim rest by 10-15 seconds and add one interval per block.",
  injury_prevention_mobility: "Progression: low load, high control, never train through sharp pain. In weeks 3-4 slow the lowering phase to 3 seconds and add a set.",
};

const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const known = new Set([...EXISTING, ...NEW_EXERCISES.map((e) => e[0])]);
const errors = [];

// ---- parse + validate
const LINE = /^([a-z0-9-]+) (\d+)x(.+?) @(\d+)(?: # (.*))?$/;
const parsed = plans.map((p) => {
  if (p.w.length !== 3) errors.push(`${p.slug}: needs exactly 3 workouts`);
  const workouts = p.w.map(([name, mins, lines], i) => {
    const ex = lines.map((line, idx) => {
      const m = LINE.exec(line);
      if (!m) { errors.push(`${p.slug}/${name}: bad line "${line}"`); return null; }
      if (!known.has(m[1])) errors.push(`${p.slug}/${name}: unknown exercise "${m[1]}"`);
      return { slug: m[1], sets: +m[2], reps: m[3], rest: +m[4], note: m[5] ?? null, order: idx + 1 };
    }).filter(Boolean);
    if (ex.length < 5 || ex.length > 7) errors.push(`${p.slug}/${name}: ${ex.length} exercises (want 5-7)`);
    const slugs = ex.map((e) => e.slug);
    if (new Set(slugs).size !== slugs.length) errors.push(`${p.slug}/${name}: duplicate exercise in one workout`);
    return { letter: LETTERS[i], name, mins, ex };
  });
  return { ...p, workouts };
});
if (new Set(plans.map((p) => p.slug)).size !== plans.length) errors.push("duplicate plan slug");
if (plans.length !== 70) errors.push(`expected 70 plans, got ${plans.length}`);
// every plan's exercise set must differ from every other plan's (guards against label-swapped templates)
const sig = new Map();
for (const p of parsed) {
  const s = [...new Set(p.workouts.flatMap((w) => w.ex.map((e) => e.slug)))].sort().join(",");
  if (sig.has(s)) errors.push(`${p.slug} has the identical exercise set to ${sig.get(s)}`);
  sig.set(s, p.slug);
}
if (errors.length) { console.error(errors.join("\n")); process.exit(1); }

// ---- emit SQL
const out = [];
out.push(`-- Position-specific, goal-based training content.
--
-- The earlier migrations added plans.goal and 5 plans per position (70 total),
-- but each plan was one thin workout plus the SAME generic circuit shared by
-- every plan, so a WR "Speed" plan and an OL "Strength" plan trained on nearly
-- identical exercises. This migration replaces that content with real,
-- position-specific programming: 3 distinct workouts per plan (Mon/Wed/Fri),
-- drawing on ${NEW_EXERCISES.length} new exercises.
--
-- Non-destructive by design:
--   * plans keep their ids and slugs (enrollments in user_plans still point at them)
--   * the 840 existing plan_workouts rows are re-pointed IN PLACE (same ids), so
--     progress_logs.plan_workout_id references stay valid
--   * old workouts are only deleted when nothing references them any more
--     (no plan_workouts row and no progress_logs row)
--   * a DO block aborts the whole migration if any expected row is missing
--
-- Generated by supabase/scripts/generate-goal-content.mjs - edit the plan
-- files there and regenerate rather than hand-editing this file.

`);

out.push("insert into public.exercises (name, slug, description, muscle_groups, equipment) values");
out.push(NEW_EXERCISES.map(([slug, name, muscles, equip, desc]) =>
  `  (${q(name)}, ${q(slug)}, ${q(desc)}, array[${muscles.split(",").map(q).join(",")}], ${q(equip)})`).join(",\n"));
out.push("on conflict (slug) do nothing;\n");

const wkRows = [];
const exRows = [];
const pwRows = [];
const planRows = [];
const nameRows = [];
for (const p of parsed) {
  const phases = p.goal === "injury_prevention_mobility" ? PHASES_CARE : PHASES;
  nameRows.push(`  (${q(p.slug)}, ${p.name ? q(p.name) : "null::text"})`);
  planRows.push(`  (${q(p.slug)}, ${q(p.desc + " " + PROGRESSION[p.goal])}, ${p.name ? q(p.name) : "null"})`);
  for (const w of p.workouts) {
    const wslug = `${p.slug}-${w.letter}`;
    wkRows.push(`  (${q(wslug)}, ${q(p.slug)}, ${q(w.name)}, ${q(`Session ${w.letter.toUpperCase()} of the plan: ${w.name}.`)}, ${w.mins})`);
    for (const e of w.ex) exRows.push(`  (${q(wslug)}, ${q(e.slug)}, ${e.order}, ${e.sets}, ${q(e.reps)}, ${e.rest}, ${e.note ? q(e.note) : "null"})`);
  }
  for (let week = 1; week <= 4; week++) {
    p.workouts.forEach((w, i) => pwRows.push(`  (${q(p.slug)}, ${week}, ${DAYS[i]}, ${q(`${p.slug}-${w.letter}`)}, ${q(`${w.name} · ${phases[week - 1]}`)})`));
  }
}
const totalEx = exRows.length;
// Plan rows without an explicit new name keep their current name; workout names use the plan's name from the DB.
out.push(`do $$
declare
  old_ids uuid[];
  n int;
begin
  select coalesce(array_agg(distinct pw.workout_id), '{}') into old_ids
  from public.plan_workouts pw join public.plans p on p.id = pw.plan_id
  where p.slug = any (array[${parsed.map((p) => q(p.slug)).join(",")}]);

  -- 1. new workouts (idempotent on slug); name prefix comes from the plan row
  insert into public.workouts (slug, name, description, sport_id, position_id, level, estimated_minutes)
  select v.wslug,
         coalesce(pn.new_name, p.name) || ' — ' || v.wname,
         v.wdesc, p.sport_id, p.position_id, p.level, v.mins
  from (values
${wkRows.join(",\n")}
  ) as v(wslug, plan_slug, wname, wdesc, mins)
  join public.plans p on p.slug = v.plan_slug
  left join (values
${nameRows.join(",\n")}
  ) as pn(plan_slug, new_name) on pn.plan_slug = p.slug
  on conflict (slug) do update set
    name = excluded.name, description = excluded.description, sport_id = excluded.sport_id,
    position_id = excluded.position_id, level = excluded.level, estimated_minutes = excluded.estimated_minutes;

  -- 2. workout exercises for the new workouts
  delete from public.workout_exercises
  where workout_id in (select id from public.workouts where slug ~ '-[abc]$' and slug = any (array[${parsed.flatMap((p) => p.workouts.map((w) => q(`${p.slug}-${w.letter}`))).join(",")}]));

  insert into public.workout_exercises (workout_id, exercise_id, order_index, sets, reps, rest_seconds, notes)
  select w.id, e.id, v.ord, v.sets, v.reps, v.rest, v.notes
  from (values
${exRows.join(",\n")}
  ) as v(wslug, eslug, ord, sets, reps, rest, notes)
  join public.workouts w on w.slug = v.wslug
  join public.exercises e on e.slug = v.eslug;
  get diagnostics n = row_count;
  if n <> ${totalEx} then raise exception 'expected ${totalEx} workout_exercises rows, inserted %', n; end if;

  -- 3. re-point the existing schedule rows in place (ids preserved)
  update public.plan_workouts pw
  set workout_id = w.id, title = v.title
  from (values
${pwRows.join(",\n")}
  ) as v(plan_slug, week_number, day_number, wslug, title)
  join public.plans p on p.slug = v.plan_slug
  join public.workouts w on w.slug = v.wslug
  where pw.plan_id = p.id and pw.week_number = v.week_number and pw.day_number = v.day_number;
  get diagnostics n = row_count;
  if n <> ${pwRows.length} then raise exception 'expected ${pwRows.length} plan_workouts rows updated, updated %', n; end if;

  -- 4. plan descriptions (and the two retitled plans)
  update public.plans p
  set description = v.description, name = coalesce(v.new_name, p.name)
  from (values
${planRows.join(",\n")}
  ) as v(plan_slug, description, new_name)
  where p.slug = v.plan_slug;
  get diagnostics n = row_count;
  if n <> ${parsed.length} then raise exception 'expected ${parsed.length} plans updated, updated %', n; end if;

  -- 5. remove the superseded workouts, but only if nothing references them
  delete from public.workouts w
  where w.id = any (old_ids)
    and not exists (select 1 from public.plan_workouts x where x.workout_id = w.id)
    and not exists (select 1 from public.progress_logs l where l.workout_id = w.id);
end $$;

-- Post-conditions: fail loudly rather than leave the library half-migrated.
do $$
begin
  if exists (select 1 from public.plans p where (select count(distinct workout_id) from public.plan_workouts where plan_id = p.id) < 3) then
    raise exception 'a plan has fewer than 3 distinct workouts';
  end if;
  if exists (select 1 from public.workouts w where not exists (select 1 from public.workout_exercises we where we.workout_id = w.id)) then
    raise exception 'a workout has no exercises';
  end if;
  if exists (select 1 from public.plan_workouts pw where not exists (select 1 from public.workouts w where w.id = pw.workout_id)) then
    raise exception 'a plan_workouts row points at a missing workout';
  end if;
end $$;
`);

writeFileSync(OUT, out.join("\n"));
const usage = new Map();
for (const p of parsed) for (const w of p.workouts) for (const e of w.ex) usage.set(e.slug, (usage.get(e.slug) ?? 0) + 1);
const unused = [...known].filter((s) => !usage.has(s));
console.log(`plans=${parsed.length} workouts=${parsed.length * 3} workout_exercises=${totalEx} schedule_rows=${pwRows.length}`);
console.log(`distinct exercises used=${usage.size} / catalog=${known.size}; unused (kept in library): ${unused.join(", ") || "none"}`);
console.log(`wrote ${OUT}`);
