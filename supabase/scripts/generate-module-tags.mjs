// Generates supabase/migrations/20260922030000_module_tags_and_backfill.sql
// Run: node supabase/scripts/generate-module-tags.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import football from "./plans-football.mjs";
import basketball from "./plans-basketball.mjs";
import soccer from "./plans-soccer.mjs";
import baseball from "./plans-baseball.mjs";

const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../migrations/20260922030000_module_tags_and_backfill.sql");
const plans = [...football, ...basketball, ...soccer, ...baseball];
const LETTERS = ["a", "b", "c"];

const CATEGORY = {
  speed: "speed_acceleration",
  strength_power: "strength",
  agility_lateral_quickness: "agility_cod",
  conditioning: "conditioning",
  injury_prevention_mobility: "mobility_injury_prevention",
};
const MODULE_INTENSITY = {
  speed_acceleration: "high", strength: "high", agility_cod: "high",
  conditioning: "moderate", mobility_injury_prevention: "low",
};
const IN_SEASON_OK = ["strength", "speed_acceleration", "agility_cod", "mobility_injury_prevention"];
const phasesFor = (cat) => {
  if (cat === "mobility_injury_prevention") return ["off_season", "pre_season", "in_season", "post_season"];
  if (cat === "conditioning") return ["off_season", "pre_season", "post_season"]; // low-intensity sessions double as post-season aerobic work
  return IN_SEASON_OK.includes(cat) ? ["off_season", "pre_season", "in_season"] : ["off_season", "pre_season"];
};
// Position-skill is a secondary tag: agility work here is position footwork
// (route breaks, drop-backs, dives...) and conditioning here mirrors the
// position's actual game demands (route tree, bullpen, two-minute drill...).
const EXTRA_SKILL = new Set(["goalkeeper-diving-catching-power"]);
const secondaryFor = (p, cat) =>
  cat === "agility_cod" || cat === "conditioning" || EXTRA_SKILL.has(p.slug) ? "position_skill" : null;

// Session-level intensity (a module can hold an easy aerobic day and a hard interval day).
function sessionIntensity(cat, name) {
  const n = name.toLowerCase();
  if (cat === "mobility_injury_prevention") return "low";
  if (cat === "conditioning") {
    if (/aerobic/.test(n)) return "low";
    if (/repeat|two-minute|match sim|shuttle|sprint|court-line|gasser|field-width|drive intervals|sled drive/.test(n)) return "high";
    return "moderate";
  }
  if (cat === "strength") return /upper|press day/.test(n) ? "moderate" : "high";
  if (cat === "agility_cod") return /footwork/.test(n) ? "moderate" : "high";
  return "high";
}

const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const planRows = [];
const wkRows = [];
const summary = {};
for (const p of plans) {
  const cat = CATEGORY[p.goal];
  const sec = secondaryFor(p, cat);
  const phases = phasesFor(cat);
  planRows.push(`  (${q(p.slug)}, ${q(cat)}, ${sec ? q(sec) : "null::text"}, ${q(MODULE_INTENSITY[cat])}, ${q("{" + phases.join(",") + "}")})`);
  p.w.forEach(([name], i) => {
    const wslug = `${p.slug}-${LETTERS[i]}`;
    const inten = sessionIntensity(cat, name);
    wkRows.push(`  (${q(wslug)}, ${q(inten)})`);
    summary[`${cat}:${inten}`] = (summary[`${cat}:${inten}`] ?? 0) + 1;
  });
}

const sql = `-- Recategorize the existing plans as modules and backfill everything the new
-- system needs. Generated by supabase/scripts/generate-module-tags.mjs.
--
-- No plan, workout, enrollment or log row is created or deleted here. Existing
-- plans keep their ids/slugs, so user_plans enrollments are unaffected. The
-- legacy plans.goal column is left exactly as it was.
--
-- Mapping: goal -> category
--   speed -> speed_acceleration      strength_power -> strength
--   agility_lateral_quickness -> agility_cod
--   conditioning -> conditioning     injury_prevention_mobility -> mobility_injury_prevention
-- Agility and conditioning modules also carry a secondary "position_skill" tag
-- (they are position-specific footwork / game-demand work).

do $$
declare n int;
begin
  -- 1. module tags for the ${plans.length} position modules
  update public.plans p
  set category = v.category::public.module_category,
      secondary_category = v.secondary::public.module_category,
      intensity = v.intensity::public.intensity_level,
      phases = v.phases::public.training_phase[]
  from (values
${planRows.join(",\n")}
  ) as v(slug, category, secondary, intensity, phases)
  where p.slug = v.slug;
  get diagnostics n = row_count;
  if n <> ${plans.length} then raise exception 'expected ${plans.length} plans tagged, tagged %', n; end if;

  -- 2. session-level intensity for the ${wkRows.length} sessions
  update public.workouts w
  set intensity = v.intensity::public.intensity_level
  from (values
${wkRows.join(",\n")}
  ) as v(slug, intensity)
  where w.slug = v.slug;
  get diagnostics n = row_count;
  if n <> ${wkRows.length} then raise exception 'expected ${wkRows.length} workouts tagged, tagged %', n; end if;

  -- 3. any plan created since (e.g. by an admin) falls back to the legacy goal mapping
  update public.plans set category = case goal
      when 'speed' then 'speed_acceleration'::public.module_category
      when 'strength_power' then 'strength'::public.module_category
      when 'agility_lateral_quickness' then 'agility_cod'::public.module_category
      when 'conditioning' then 'conditioning'::public.module_category
      else 'mobility_injury_prevention'::public.module_category end
  where category is null;
  update public.plans set intensity = case category
      when 'mobility_injury_prevention' then 'low'::public.intensity_level
      when 'conditioning' then 'moderate'::public.intensity_level
      else 'high'::public.intensity_level end
  where intensity is null;
end $$;

alter table public.plans
  alter column category set not null,
  alter column intensity set not null;

-- 4. history: existing progress logs inherit the category/intensity/module of
-- the scheduled workout they were done from (no log row is otherwise changed).
update public.progress_logs l
set plan_id = pw.plan_id,
    category = p.category,
    intensity = coalesce(w.intensity, p.intensity)
from public.plan_workouts pw
join public.plans p on p.id = pw.plan_id
left join public.workouts w on w.id = pw.workout_id
where l.plan_workout_id = pw.id and l.plan_id is null;

-- Post-conditions
do $$
begin
  if exists (select 1 from public.plans where category is null or intensity is null) then
    raise exception 'a plan is missing its category or intensity';
  end if;
  -- every position that has modules must have at least one in each of the five core categories
  if exists (
    select 1 from public.positions pos
    where exists (select 1 from public.plans p where p.position_id = pos.id)
      and (select count(distinct p.category) from public.plans p where p.position_id = pos.id
             and p.category in ('strength','speed_acceleration','agility_cod','conditioning','mobility_injury_prevention')) < 5
  ) then
    raise exception 'a position is missing a core module category';
  end if;
end $$;
`;
writeFileSync(OUT, sql);
console.log("wrote", OUT);
console.log("session intensity mix:", JSON.stringify(summary, null, 1));
